#pragma once

#include "fellow_motion_service.h"

#include "scene/3d/node_3d.h"

class Skeleton3D;

// A character whose whole-body motion is generated by the neural motion model (docs/decisions/0143-neural-motion.md):
// give it a desired velocity each frame and it walks, jogs, runs, turns and stops — each segment of 0.6-1.9 s generated
// from the four poses it last showed towards a target ahead of it (root-only: where and how fast; the model fills in
// the body), the next one requested before the segment's transition point and crossfaded in when it arrives (the
// requests of all characters of a model run as one batch on its own GPU device). Standing still it generates small
// idle segments towards a relaxed stance. It moves itself: its origin follows the hips on the ground, its +Z the facing.
class FellowMotionCharacter3D : public Node3D {
	GDCLASS(FellowMotionCharacter3D, Node3D);

public:
	enum MotionState {
		STATE_IDLE,
		STATE_LOCOMOTION,
	};
	enum InferenceMode {
		INFERENCE_ASYNC, // the service's worker thread runs the requests as they come; results on a later frame
		INFERENCE_FLUSH, // requests wait for flush_requests() (all characters' as one batch); results the next frame
		INFERENCE_IMMEDIATE, // each request runs at once on this thread (a batch of one; no latency)
	};

private:
	using Xf = FellowMotionRig::Xf;

	struct Segment {
		LocalVector<Xf> frames;
		LocalVector<float> contacts;
		int count = 0;
		int transition_early = 0;
		bool get_up = false; // towards a standing pose from the ground: not re-planned before its transition
		double time = 0.0;
		bool valid() const { return count > 0; }
		double duration() const { return MAX(0, count - 1 - transition_early) / 30.0; }
		double time_to_transition() const { return MAX(0.0, duration() - time); }
	};

	String model_path;
	String body_path;
	Vector3 desired_velocity;
	float max_speed = 3.5f;
	int transition_early_frames = 8;
	int min_tokens = 8;
	int max_tokens = 14;
	float lead_time = 0.97f;
	float speed_halflife = 0.1f;
	bool catch_up = true;
	InferenceMode inference_mode = INFERENCE_ASYNC;
	bool auto_process = true;
	float crossfade_time = 0.15f;
	int max_batch = 32;
	Color body_color = Color(0.62, 0.66, 0.72);
	bool idle_motion = true;
	bool get_up = true;

	Ref<FellowMotionService> service;
	const FellowMotionRig *rig = nullptr;
	String error;
	bool started = false;
	float ground_y = 0.0f;

	// Shown pose and its history (motion space: the ground at y = 0).
	LocalVector<Xf> pose;
	LocalVector<Xf> history; // [32][J], a ring: logical slot i (0 the oldest) at (history_head + i) % 32
	int history_head = 0;
	LocalVector<Xf> fade_pose; // the old segment's pose while crossfading
	float history_dt[32] = {};
	LocalVector<Xf> relaxed;
	int head_joint = -1;
	float stand_hips_y = 0.97f; // the relaxed stance's hips and head heights
	float stand_head_y = 1.6f;

	Segment seg;
	Segment old_seg;
	double fade = 1.0; // 0 -> 1 while the old segment fades out

	// The request in flight.
	uint64_t pending_id = 0;
	double pending_time = 0.0; // seconds since it was made
	bool pending_idle = false;
	bool pending_get_up = false;
	double latency = 0.05; // the measured request -> result time (EMA)

	// Movement (MotionBricks' MovementControl, 1D: the facing follows the velocity).
	float vel_angle = 0.0f;
	float vel_angle_rate = 0.0f;
	float speed = 0.0f;
	float speed_rate = 0.0f;
	float input_speed = 0.0f;
	float input_angle = 0.0f;
	Vector3 prev_gen_velocity;
	Vector3 actual_velocity;
	float shown_speed = 0.0f;
	Vector3 last_ground;
	bool force_regen = true;
	MotionState state = STATE_IDLE;

	// Body.
	Node3D *body = nullptr;
	Skeleton3D *skeleton = nullptr;
	LocalVector<int> bone_of_joint;
	bool bones_set = false; // every bone posed once (the joints the model does not drive need it only once)

	// Statistics.
	uint64_t generations = 0;
	uint64_t get_ups = 0;
	double latency_sum = 0.0;

	void _start();
	void _load_body();
	void _apply_to_skeleton(bool p_all = false);
	void _update_movement(double p_delta);
	bool _needs_regeneration() const;
	void _generate(bool p_idle);
	void _accept(FellowMotionService::Result &p_result);
	void _sample(const Segment &p_seg, Xf *r_pose) const;
	void _record(double p_delta);
	void _context(Xf *r_context) const;
	Vector3 _ground() const;
	float _heading_of(const Xf *p_local) const;
	bool _is_down(const Xf *p_local) const;
	void _process(double p_delta);

protected:
	void _notification(int p_what);
	static void _bind_methods();

public:
	PackedStringArray get_configuration_warnings() const override;

	void set_model_path(const String &p_path);
	String get_model_path() const { return model_path; }
	void set_body_path(const String &p_path);
	String get_body_path() const { return body_path; }
	void set_desired_velocity(const Vector3 &p_v) { desired_velocity = p_v; }
	Vector3 get_desired_velocity() const { return desired_velocity; }
	void set_max_speed(float p_v) { max_speed = MAX(0.1f, p_v); }
	float get_max_speed() const { return max_speed; }
	void set_transition_early_frames(int p_v) { transition_early_frames = CLAMP(p_v, 0, 20); }
	int get_transition_early_frames() const { return transition_early_frames; }
	void set_min_tokens(int p_v) { min_tokens = CLAMP(p_v, 6, 16); }
	int get_min_tokens() const { return min_tokens; }
	void set_max_tokens(int p_v) { max_tokens = CLAMP(p_v, 6, 16); }
	int get_max_tokens() const { return max_tokens; }
	void set_catch_up(bool p_v) { catch_up = p_v; }
	bool is_catch_up() const { return catch_up; }
	void set_speed_halflife(float p_v) { speed_halflife = CLAMP(p_v, 0.01f, 2.0f); }
	float get_speed_halflife() const { return speed_halflife; }
	void set_lead_time(float p_v) { lead_time = MAX(0.1f, p_v); }
	float get_lead_time() const { return lead_time; }
	void set_inference_mode(InferenceMode p_v) { inference_mode = p_v; }
	InferenceMode get_inference_mode() const { return inference_mode; }
	void set_auto_process(bool p_v);
	bool is_auto_process() const { return auto_process; }
	void advance(double p_delta);
	static void flush_requests(const String &p_model_path);
	void set_crossfade_time(float p_v) { crossfade_time = MAX(0.0f, p_v); }
	float get_crossfade_time() const { return crossfade_time; }
	void set_max_batch(int p_v) { max_batch = CLAMP(p_v, 1, 256); }
	int get_max_batch() const { return max_batch; }
	void set_body_color(const Color &p_c);
	Color get_body_color() const { return body_color; }
	void set_idle_motion(bool p_v) { idle_motion = p_v; }
	bool is_idle_motion() const { return idle_motion; }
	void set_get_up(bool p_v) { get_up = p_v; }
	bool is_get_up() const { return get_up; }

	Vector3 get_actual_velocity() const { return actual_velocity; }
	MotionState get_state() const { return state; }
	bool is_ready() const { return started && rig != nullptr; }
	String get_error() const { return error; }
	PackedVector3Array get_joint_positions() const; // world, the shown pose
	Dictionary get_stats() const;
	static Dictionary get_service_stats(const String &p_model_path);

	FellowMotionCharacter3D();
	~FellowMotionCharacter3D();
};

VARIANT_ENUM_CAST(FellowMotionCharacter3D::MotionState);
VARIANT_ENUM_CAST(FellowMotionCharacter3D::InferenceMode);

void fellow_motion_clear_body_cache();
